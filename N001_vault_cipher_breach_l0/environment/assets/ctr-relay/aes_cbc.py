def _inv_sub_bytes(state):
    for r in range(4):
        for c in range(4):
            state[r][c] = SBOX_INV[state[r][c]]


def _inv_shift_rows(state):
    state[1] = state[1][-1:] + state[1][:-1]
    state[2] = state[2][-2:] + state[2][:-2]
    state[3] = state[3][-3:] + state[3][:-3]


def _inv_mix_columns(state):
    for c in range(4):
        s0, s1, s2, s3 = state[0][c], state[1][c], state[2][c], state[3][c]
        state[0][c] = _mul(0x0e, s0) ^ _mul(0x0b, s1) ^ _mul(0x0d, s2) ^ _mul(0x09, s3)
        state[1][c] = _mul(0x09, s0) ^ _mul(0x0e, s1) ^ _mul(0x0b, s2) ^ _mul(0x0d, s3)
        state[2][c] = _mul(0x0d, s0) ^ _mul(0x09, s1) ^ _mul(0x0e, s2) ^ _mul(0x0b, s3)
        state[3][c] = _mul(0x0b, s0) ^ _mul(0x0d, s1) ^ _mul(0x09, s2) ^ _mul(0x0e, s3)


def _mul(a, b):
    r = 0
    for _ in range(8):
        if b & 1:
            r ^= a
        hi = a & 0x80
        a = (a << 1) & 0xff
        if hi:
            a ^= 0x1b
        b >>= 1
    return r


from aes import _key_expansion, _add_round_key, _sub_bytes, _shift_rows, _mix_columns, Nr


def _decrypt_block(block, w):
    state = [list(block[4 * c:4 * c + 4]) for c in range(4)]
    state = [[state[r][c] for r in range(4)] for c in range(4)]
    _add_round_key(state, w, Nr)
    for rnd in range(Nr - 1, 0, -1):
        _inv_shift_rows(state)
        _inv_sub_bytes(state)
        _add_round_key(state, w, rnd)
        _inv_mix_columns(state)
    _inv_shift_rows(state)
    _inv_sub_bytes(state)
    _add_round_key(state, w, 0)
    out = bytearray(16)
    for c in range(4):
        for r in range(4):
            out[4 * c + r] = state[r][c]
    return bytes(out)


def aes_ecb_decrypt_block(key, block):
    w = _key_expansion(key)
    return _decrypt_block(block, w)


def pkcs7_pad(data, block_size=16):
    pad_len = block_size - (len(data) % block_size)
    return data + bytes([pad_len]) * pad_len


def pkcs7_unpad(data, block_size=16):
    if not data or len(data) % block_size != 0:
        raise ValueError("invalid length")
    pad_len = data[-1]
    if pad_len < 1 or pad_len > block_size:
        raise ValueError("invalid padding")
    if data[-pad_len:] != bytes([pad_len]) * pad_len:
        raise ValueError("invalid padding")
    return data[:-pad_len]


def aes_cbc_encrypt(key, iv, plaintext):
    padded = pkcs7_pad(plaintext)
    blocks = [padded[i:i+16] for i in range(0, len(padded), 16)]
    ct = bytearray()
    prev = iv
    for block in blocks:
        xored = bytes(a ^ b for a, b in zip(block, prev))
        enc = aes_ecb_encrypt_block(key, xored)
        ct.extend(enc)
        prev = enc
    return bytes(iv) + bytes(ct)


def aes_cbc_decrypt_raw(key, iv, ciphertext):
    blocks = [ciphertext[i:i+16] for i in range(0, len(ciphertext), 16)]
    pt = bytearray()
    prev = iv
    for block in blocks:
        dec = aes_ecb_decrypt_block(key, block)
        pt.extend(bytes(a ^ b for a, b in zip(dec, prev)))
        prev = block
    return bytes(pt)
